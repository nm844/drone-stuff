#!/usr/bin/env python3
"""Generate include/duml/commands.hpp: one named constant per known (cmd_set, cmd_id)."""
import json, re, sys, collections

src, out = sys.argv[1], sys.argv[2]
cmds = json.load(open(src))
NS = {0:'general',1:'special',2:'camera',3:'flight_control',4:'gimbal',5:'center_board',6:'remote_control',
      7:'wifi',8:'dm36x',9:'hd_link',10:'vision',11:'simulator',12:'esc',13:'battery',14:'data_logger',
      15:'rtk',16:'automation',17:'adsb'}

def camel(name):
    words = re.findall(r'[A-Za-z0-9]+', name)
    s = ''.join(w[0].upper() + w[1:] for w in words) or 'Unnamed'
    return 'k' + (s if not s[0].isdigit() else '_' + s)

lines = ['// GENERATED by tools/gen_cpp_constants.py from commands.json -- do not hand-edit.',
         '// One named constant per known DUML command id, grouped by command set.',
         '#pragma once', '#include <cstdint>', '', 'namespace duml {', 'namespace cmd {', '']
for cs in sorted(NS):
    group = sorted((c for c in cmds if c['cmd_set'] == cs), key=lambda c: c['cmd_id'])
    if not group: continue
    lines.append(f'namespace {NS[cs]} {{')
    lines.append(f'constexpr uint8_t kCmdSet = 0x{cs:02X};')
    seen = collections.Counter()
    for c in group:
        ident = camel(c['name'])
        seen[ident] += 1
        if seen[ident] > 1: ident += f"_{c['cmd_id']:02X}"
        flag = 'decoded' if c['decode_status'] == 'full' else 'name only'
        lines.append(f"constexpr uint8_t {ident} = 0x{c['cmd_id']:02X};  // {c['name']} ({flag})")
    lines.append(f'}} // namespace {NS[cs]}')
    lines.append('')
lines += ['} // namespace cmd', '} // namespace duml', '']
open(out, 'w').write('\n'.join(lines))
print('wrote', out, file=sys.stderr)
