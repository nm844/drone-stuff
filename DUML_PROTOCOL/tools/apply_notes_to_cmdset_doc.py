#!/usr/bin/env python3
"""
Hand-maintained cmdset_XX_*.md docs aren't regenerated by render_docs.py (it
only knows the original Lua dissector data). This script does the narrow,
mechanical part of updating one such doc after a payload-decode sweep: for
each "## 0xXX — Name" section currently showing the generic placeholder
line, replace it with either a real field table + worked example (if
commands.json now has decode_status=="full" with source=="binary_re" for
that cmd_id) or the research note commands.json now carries for it.

Usage: python3 DUML_PROTOCOL/tools/apply_notes_to_cmdset_doc.py <cmd_set_decimal> <cmdset_doc_path>
"""
import json
import re
import sys

PLACEHOLDER = "_No byte-level payload decoder in source dissector (name-only / unparsed payload)._"
# Some sections carry a hand-edited variant of the placeholder (e.g. appending
# "-- but independently binary-confirmed live on this firmware" from a prior,
# pre-payload-decode-sweep pass, sometimes line-wrapped) -- match on the
# stable prefix through the closing "_" rather than requiring an exact string
# match of the canonical form, so those sections aren't silently skipped.
PLACEHOLDER_RE = re.compile(r'_No byte-level payload decoder in source dissector.*?_\n', re.S)


def render_full(entry):
    lines = [f"Payload decoder (binary RE, this project's own disassembly — not from the public dissector): `{entry['dissector_fn']}`\n"]
    lines.append("  | Off | Size | Field | Type | Notes |")
    lines.append("  |---|---|---|---|---|")
    for f in entry['fields']:
        notes = f.get('desc') or ''
        lines.append(f"  | {f['offset']} | {f['size']} | `{f['name']}` ({f['label']}) | {f['type']} | {notes} |")
    lines.append("")
    ex = entry.get('_example')
    if ex:
        lines.append("**Worked example:**\n")
        lines.append(f"- Request payload: `{ex.get('example_request_hex','')}`")
        lines.append(f"  {ex.get('example_request_explanation','')}")
        resp = ex.get('example_response_hex') or ''
        if resp:
            lines.append(f"- Response payload: `{resp}`")
            lines.append(f"  {ex.get('example_response_explanation','')}")
        else:
            lines.append(f"- Response: {ex.get('example_response_explanation', 'no distinct response payload')}")
        lines.append("")
    return '\n'.join(lines)


def render_note(note):
    return f"_Not decoded._ {note}\n"


def main():
    cmd_set = int(sys.argv[1])
    doc_path = sys.argv[2]
    wave_output = sys.argv[3] if len(sys.argv) > 3 else None

    commands = json.load(open('duml_py/duml/commands.json'))
    by_id = {c['cmd_id']: c for c in commands if c['cmd_set'] == cmd_set}

    examples_by_id = {}
    if wave_output:
        wave = json.load(open(wave_output))
        result = wave.get('result', wave)
        for cmd in result['all_commands']:
            cs_hex = cmd.get('cmd_set_hex')
            cs = int(cs_hex, 16) if cs_hex else cmd_set
            if cs == cmd_set and cmd['status'] == 'decoded':
                examples_by_id[int(cmd['cmd_id_hex'], 16)] = cmd

    text = open(doc_path).read()
    sections = re.split(r'(?=^## 0x[0-9A-Fa-f]+ —)', text, flags=re.M)
    out = [sections[0]]
    n_full, n_note, n_skip = 0, 0, 0
    for sec in sections[1:]:
        m = re.match(r'^## (0x[0-9A-Fa-f]+) — (.*)\n', sec)
        if not m:
            out.append(sec)
            continue
        cmd_id = int(m.group(1), 16)
        entry = by_id.get(cmd_id)
        ph_match = PLACEHOLDER_RE.search(sec)
        if entry is None or ph_match is None:
            out.append(sec)
            n_skip += 1
            continue
        if entry['decode_status'] == 'full' and entry.get('source') == 'binary_re':
            entry['_example'] = examples_by_id.get(cmd_id)
            replacement = render_full(entry)
            n_full += 1
        elif entry.get('note'):
            replacement = render_note(entry['note'])
            n_note += 1
        else:
            out.append(sec)
            n_skip += 1
            continue
        sec = sec[:ph_match.start()] + replacement + sec[ph_match.end():]
        out.append(sec)

    open(doc_path, 'w').write(''.join(out))
    print(f"Updated {doc_path}: {n_full} full decodes, {n_note} notes, {n_skip} left as-is", file=sys.stderr)


if __name__ == '__main__':
    main()
